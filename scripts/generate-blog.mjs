import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = path.join(root, "content/posts");
const files = (await readdir(directory))
  .filter((name) => name.endsWith(".json"))
  .sort();
const entries = [];
for (const filename of files) {
  const slug = filename.slice(0, -5);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug))
    throw new Error(`Invalid blog slug: ${slug}`);
  const post = JSON.parse(
    await readFile(path.join(directory, filename), "utf8"),
  );
  const body = await readFile(path.join(directory, `${slug}.mdx`), "utf8");
  if (
    typeof post.title !== "string" ||
    !post.title.trim() ||
    typeof post.description !== "string" ||
    !post.description.trim() ||
    typeof post.category !== "string" ||
    typeof post.published !== "boolean"
  )
    throw new Error(`Incomplete metadata in ${filename}`);
  if (
    post.published &&
    (!/^\d{4}-\d{2}-\d{2}$/.test(post.publishedAt || "") ||
      !Number.isFinite(Date.parse(post.publishedAt)))
  )
    throw new Error(
      `Published posts need a valid YYYY-MM-DD date: ${filename}`,
    );
  const readingMinutes = Math.max(
    1,
    Math.ceil([body, ...(post.faq || []).map((item) => `${item.question} ${item.answer}`)].join(" ").trim().split(/\s+/).length / 200),
  );
  if (
    post.image != null &&
    (typeof post.image.src !== "string" ||
      !post.image.src.startsWith("/") ||
      post.image.src.startsWith("//") ||
      typeof post.image.alt !== "string" ||
      !post.image.alt.trim() ||
      !Number.isInteger(post.image.width) ||
      post.image.width <= 0 ||
      !Number.isInteger(post.image.height) ||
      post.image.height <= 0)
  )
    throw new Error(`Blog images need a public path, alt text and positive dimensions: ${filename}`);
  entries.push({
    slug,
    title: post.title,
    description: post.description,
    category: post.category,
    published: post.published,
    publishedAt: post.publishedAt || null,
    projectSlug: post.projectSlug || null,
    readingTime: `${readingMinutes} min read`,
    status: post.published ? "Article" : "Draft preview",
    seoTitle: typeof post.seoTitle === "string" ? post.seoTitle : null,
    keywords: Array.isArray(post.keywords) ? post.keywords : [],
    tags: Array.isArray(post.tags) ? post.tags : [],
    image: post.image || null,
    faq: Array.isArray(post.faq) ? post.faq : [],
  });
}
const source = `// Generated by scripts/generate-blog.mjs. Edit the MDX and JSON files in content/posts/.\nexport const postIndex = [\n${entries.map((post) => `  { ...${JSON.stringify(post)}, load: () => import("./posts/${post.slug}.mdx") }`).join(",\n")}\n];\n`;
const output = path.join(root, "content/blog-index.generated.ts");
let previous = "";
try {
  previous = await readFile(output, "utf8");
} catch {
  /* First generation. */
}
if (source !== previous) await writeFile(output, source);
console.log(
  `Blog index ready: ${entries.length} post${entries.length === 1 ? "" : "s"}.`,
);
